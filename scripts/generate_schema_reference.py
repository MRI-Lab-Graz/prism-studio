"""Write the field tables in docs/specs/*.md from app/schemas/stable/*.schema.json.

The schema is the one source of truth; the prose around each table stays hand-written.
Usage: python scripts/generate_schema_reference.py
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = REPO_ROOT / "app" / "schemas" / "stable"
SPECS = REPO_ROOT / "docs" / "specs"

BEGIN = "<!-- BEGIN SCHEMA REFERENCE (generated by scripts/generate_schema_reference.py; do not edit) -->"
END = "<!-- END SCHEMA REFERENCE -->"

# schema name -> spec page
PAGES = {
    "survey": "survey.md",
    "biometrics": "biometrics.md",
    "biosample": "biosample.md",
    "events": "events.md",
    "environment": "environment.md",
    "physio": "physio.md",
    "eyetracking": "eyetracking.md",
    "project": "project.md",
    "dataset_description": "dataset_description.md",
}
# Schemas documented elsewhere (grammar, recipes, internal index).
OTHER_DOCS = {"entities", "recipe.survey", "instrument-registry", "tool-limesurvey"}

MAX_DEPTH = 4
MAX_DESC = 160


def _type(node):
    t = node.get("type", "") if isinstance(node, dict) else ""
    return " / ".join(t) if isinstance(t, list) else t


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _detail(node):
    if not isinstance(node, dict):
        return ""
    desc = _cell(node.get("description", ""))
    if len(desc) > MAX_DESC:
        desc = desc[: MAX_DESC - 1].rstrip() + "…"
    if "enum" in node:
        values = ", ".join(f"`{v}`" for v in node["enum"])
        desc = f"{desc} Allowed: {values}.".strip()
    return desc


def schema_rows(schema, prefix="", depth=0):
    """Flatten a JSON schema to (path, type, required, detail) rows, depth-first."""
    rows = []
    required = set(schema.get("required", []))
    for name, node in (schema.get("properties") or {}).items():
        path = f"{prefix}{name}"
        rows.append(
            (path, _type(node), "yes" if name in required else "no", _detail(node))
        )
        if depth + 1 >= MAX_DEPTH:
            continue
        if not isinstance(node, dict):
            continue
        child = node
        if isinstance(node.get("items"), dict):
            child, path = node["items"], f"{path}[]"
        rows += schema_rows(child, f"{path}.", depth + 1)
        for pattern, sub in (node.get("patternProperties") or {}).items():
            rows.append((f"{path}.<{pattern}>", _type(sub), "no", _detail(sub)))
            if isinstance(sub, dict):
                rows += schema_rows(sub, f"{path}.<{pattern}>.", depth + 1)
    for pattern, sub in (schema.get("patternProperties") or {}).items():
        rows.append((f"{prefix}<{pattern}>", _type(sub), "no", _detail(sub)))
    return rows


def render(name):
    schema = json.loads((SCHEMAS / f"{name}.schema.json").read_text(encoding="utf-8"))
    lines = [
        BEGIN,
        "",
        f"## Field reference (`{name}.schema.json`, version {schema.get('version', '?')})",
        "",
        "Generated from [`app/schemas/stable/"
        f"{name}.schema.json`](../../app/schemas/stable/{name}.schema.json). "
        "Nested fields are shown as `Block.Field`; `[]` marks list items. "
        "*Required* applies within its parent block.",
        "",
        "| Field | Type | Required | Description |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| `{p}` | {t} | {r} | {d} |" for p, t, r, d in schema_rows(schema)]
    lines += ["", END]
    return "\n".join(lines)


def sync(write=True):
    """Replace each page's generated block; return the pages that were (or would be) changed."""
    stale = []
    for name, page in PAGES.items():
        path = SPECS / page
        text = path.read_text(encoding="utf-8")
        head, rest = text.split(BEGIN, 1)
        new = head + render(name) + rest.split(END, 1)[1]
        if new != text:
            stale.append(page)
            if write:
                path.write_text(new, encoding="utf-8")
    return stale


if __name__ == "__main__":
    print("changed:", ", ".join(sync()) or "none")
